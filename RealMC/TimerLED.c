#include "stm32f446xx.h"
// Connect LED to pin D13 in the nucleo board.

static void gpio_led_init(void)
{
    /* Enable GPIOA clock */
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOAEN;

    /* PA5 -> output mode */
    GPIOA->MODER &= ~(3U << (5U * 2U));
    GPIOA->MODER |=  (1U << (5U * 2U));

    /* Optional: push-pull, no pull-up/pull-down */
    GPIOA->OTYPER &= ~(1U << 5);
    GPIOA->PUPDR  &= ~(3U << (5U * 2U));
}

static void tim3_init_500ms(void)
{
    /* Enable TIM3 clock */
    RCC->APB1ENR |= RCC_APB1ENR_TIM3EN;

    /*
       Assuming timer clock = 16 MHz
       (default after reset if you are not reconfiguring clocks)

       Step 1: Prescaler
       16 MHz / 16000 = 1000 Hz
       -> 1 tick = 1 ms
    */
    TIM3->PSC = 16000 - 1;

    /*
       Step 2: Auto-reload register

       500 ticks × 1 ms = 500 ms
    */
    TIM3->ARR = 500 - 1; //500, 100

    /* Reset counter */
    TIM3->CNT = 0;

    /* Apply PSC and ARR immediately */
    TIM3->EGR |= TIM_EGR_UG;

    /* Clear pending update flag generated by UG */
    TIM3->SR &= ~TIM_SR_UIF;

    /* Start timer */
    TIM3->CR1 |= TIM_CR1_CEN;
}

int main(void)
{
    gpio_led_init();
    tim3_init_500ms();

    while (1)
    {
        /* Wait until update event */
        while (!(TIM3->SR & TIM_SR_UIF));

        /* Clear update flag */
        TIM3->SR &= ~TIM_SR_UIF;

        /* Toggle LED */
        GPIOA->ODR ^= (1U << 5);
    }
}
